const COPY: Record<SettingsLocale, Copy> = { tr: TR, en: EN };

export type SettingsCopy = Copy;

export function getSettingsCopy(locale: SettingsLocale): SettingsCopy {
  return COPY[locale];
}

export function useSettingsCopy(): { copy: SettingsCopy; locale: SettingsLocale } {
  const locale = useDsLocale();
  return { copy: COPY[locale], locale };
}

/** Sunucu hata kodu → kullanıcının dilinde metin. */
export function errorText(copy: SettingsCopy, code: string | undefined, fallback: string | undefined): string {
  switch (code) {
    case 'AVATAR_NOT_ALLOWED':
      return copy.locale === 'en' ? 'This avatar cannot be used. Pick one from the list.' : 'Bu avatar seçilemez. Listeden bir avatar seç.';
    case 'REAUTH_PASSWORD':
      return copy.locale === 'en' ? 'Password is incorrect or missing.' : 'Şifre hatalı ya da girilmedi.';
    case 'REAUTH_TOTP':
      return copy.locale === 'en' ? 'The authenticator code is wrong or expired.' : 'Doğrulama kodu hatalı ya da süresi geçmiş.';
    case 'REAUTH_RECENT_LOGIN':
      return copy.deleteRecentLogin;
    case 'EMAIL_MISMATCH':
      return copy.locale === 'en' ? 'The email does not match your account.' : 'E-posta hesabınla eşleşmiyor.';
    case 'RATE_LIMITED':
      return copy.locale === 'en' ? 'Too many attempts. Please try again later.' : 'Çok fazla deneme. Biraz sonra tekrar dene.';
    case 'INVALID_DATE':
      return copy.birthdayInvalid;
    default:
      return fallback || copy.genericError;
  }
}
