const COPY: Record<DsLocale, WalletCopy> = { tr, en };

export function useWalletCopy(): WalletCopy {
  return COPY[useDsLocale()];
}

export function getWalletCopy(locale: DsLocale = 'tr'): WalletCopy {
  return COPY[locale];
}
