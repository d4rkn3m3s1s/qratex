/**
 * Ben kabuğu + İlerleme metinleri (TR/EN). Saf; sunucu (`getServerLocale`) ve istemci
 * (`useAppLocale`) aynı sözlüğü kullanır. QDL kiti (`components/ds/*`) ile aynı desen:
 * paylaşılan `messages/*.json` yerine yüzeye özgü, tipli sözlük.
 */
export type MeLocale = 'tr' | 'en';

export function toMeLocale(value: unknown): MeLocale {
  return value === 'en' ? 'en' : 'tr';
}

export function localeTag(locale: MeLocale): string {
  return locale === 'en' ? 'en-US' : 'tr-TR';
}

export function formatNumber(n: number, locale: MeLocale, opts?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(localeTag(locale), opts).format(n);
}

export function formatDate(iso: string, locale: MeLocale, opts: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(localeTag(locale), { timeZone: 'Europe/Istanbul', ...opts }).format(new Date(iso));
}

