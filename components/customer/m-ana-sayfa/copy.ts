const COPY: Record<DsLocale, HomeCopy> = { tr, en };

export type { HomeCopy };

export function useHomeCopy(): { copy: HomeCopy; locale: DsLocale } {
  const locale = useDsLocale();
  return { copy: COPY[locale], locale };
}

export function getHomeCopy(locale: DsLocale = 'tr'): HomeCopy {
  return COPY[locale];
}
