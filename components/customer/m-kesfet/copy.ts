export type PlacesCopy = Copy;
export type PlacesLocale = 'tr' | 'en';

export function getPlacesCopy(locale: string | null | undefined): PlacesCopy {
  return locale === 'en' ? en : tr;
}

export function usePlacesCopy(): { copy: PlacesCopy; locale: PlacesLocale } {
  const { locale } = useAppLocale();
  const l: PlacesLocale = locale === 'en' ? 'en' : 'tr';
  return { copy: l === 'en' ? en : tr, locale: l };
}
