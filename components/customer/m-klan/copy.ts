const COPY: Record<DsLocale, Copy> = { tr, en };

export type KlanCopy = Copy;

export function useKlanCopy(): KlanCopy {
  return COPY[useDsLocale()];
}

export function useKlanLocale(): { locale: DsLocale; tag: 'tr-TR' | 'en-US' } {
  const locale = useDsLocale();
  return { locale, tag: locale === 'en' ? 'en-US' : 'tr-TR' };
}

/** Sunucu hata koduna göre yerel mesaj; bilinmeyen kodda sunucunun Türkçe mesajı. */
export function squadErrorText(locale: DsLocale, code: string | undefined, fallback: string): string {
  if (code && isSquadErrorCode(code)) return SQUAD_ERROR_MESSAGES[locale][code];
  return fallback;
}
