export type VoicesCopy = Copy;
export type VoicesLocale = 'tr' | 'en';

export function useVoicesLocale(): VoicesLocale {
  return useDsLocale();
}

export function useVoicesCopy(): Copy {
  return useDsLocale() === 'en' ? en : tr;
}

/** Bilinmeyen konu anahtarı sessizce atılmaz: ilk harfi büyütülerek gösterilir. */
export function topicLabel(key: string, locale: VoicesLocale): string {
  const k = key.trim().toLowerCase();
  const hit = TOPICS[locale][k];
  if (hit) return hit;
  return k ? k.charAt(0).toLocaleUpperCase(locale === 'tr' ? 'tr-TR' : 'en-US') + k.slice(1) : key;
}
