/**
 * Hata metni: bilinen kod → yerel metin. Doğrulama/kilit hatalarında sunucunun ayrıntılı
 * (soru numaralı) Türkçe mesajı TR arayüzde daha bilgilendiricidir; EN'de genel metne düşülür.
 */
export function errorText(copy: SurveyCopy, locale: DsLocale, err: unknown): string {
  const e = err as { code?: string; message?: string; status?: number } | null;
  const code = e?.code ?? '';
  const known = copy.errors[code];
  if (known) return known;
  if ((code === 'VALIDATION' || code === 'STRUCTURE_LOCKED') && e?.message && locale === 'tr') return e.message;
  if (locale === 'tr' && e?.message && !/^HTTP \d+$/.test(e.message) && e.status && e.status < 500) return e.message;
  return copy.errors.generic ?? '';
}

export function formatNumber(n: number, tag: string, fractionDigits = 0): string {
  return new Intl.NumberFormat(tag, { maximumFractionDigits: fractionDigits, minimumFractionDigits: fractionDigits }).format(n);
}

export function formatPct(n: number | null, tag: string): string {
  if (n == null) return '—';
  return new Intl.NumberFormat(tag, { style: 'percent', maximumFractionDigits: 0 }).format(n / 100);
}

export function formatDate(iso: string, tag: string): string {
  return new Intl.DateTimeFormat(tag, { timeZone: 'Europe/Istanbul', day: 'numeric', month: 'short', year: 'numeric' }).format(new Date(iso));
}

export function formatDateTime(iso: string, tag: string): string {
  return new Intl.DateTimeFormat(tag, {
    timeZone: 'Europe/Istanbul',
    day: 'numeric',
    month: 'short',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
  }).format(new Date(iso));
}

/** Göreli zaman ("3 saat önce"). `now` dışarıdan gelir (hidrasyon tutarlılığı). */
export function formatRelative(iso: string, tag: string, now: number): string {
  const diffSec = Math.round((new Date(iso).getTime() - now) / 1000);
  const rtf = new Intl.RelativeTimeFormat(tag, { numeric: 'auto' });
  const abs = Math.abs(diffSec);
  if (abs < 60) return rtf.format(Math.round(diffSec), 'second');
  if (abs < 3600) return rtf.format(Math.round(diffSec / 60), 'minute');
  if (abs < 86_400) return rtf.format(Math.round(diffSec / 3600), 'hour');
  if (abs < 30 * 86_400) return rtf.format(Math.round(diffSec / 86_400), 'day');
  if (abs < 365 * 86_400) return rtf.format(Math.round(diffSec / (30 * 86_400)), 'month');
  return rtf.format(Math.round(diffSec / (365 * 86_400)), 'year');
}
