/**
 * Kampanya merkezi metinleri (TR/EN). Saf; sunucu (`getServerLocale`) ve istemci
 * (`useAppLocale`) aynı sözlüğü kullanır (QDL kiti deseni: yüzeye özgü tipli sözlük).
 */
import type { CampaignSegmentKey, CampaignStatus, ListTab } from './domain';

export type CampaignLocale = 'tr' | 'en';

export function toCampaignLocale(v: unknown): CampaignLocale {
  return v === 'en' ? 'en' : 'tr';
}

export function localeTag(l: CampaignLocale): string {
  return l === 'en' ? 'en-US' : 'tr-TR';
}

export function fmtNumber(n: number, l: CampaignLocale, opts?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(localeTag(l), opts).format(n);
}

export function fmtMoney(n: number, l: CampaignLocale): string {
  return new Intl.NumberFormat(localeTag(l), { style: 'currency', currency: 'TRY', maximumFractionDigits: 0 }).format(n);
}

export function fmtPct(n: number | null, l: CampaignLocale): string {
  if (n == null) return '—';
  const v = fmtNumber(n, l, { maximumFractionDigits: 1 });
  return l === 'en' ? `${v}%` : `%${v}`;
}

export function fmtDate(iso: string, l: CampaignLocale, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short', year: 'numeric' }): string {
  return new Intl.DateTimeFormat(localeTag(l), { timeZone: 'Europe/Istanbul', ...opts }).format(new Date(iso));
}

export function fmtDateTime(iso: string, l: CampaignLocale): string {
  return fmtDate(iso, l, { day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' });
}

/** YYYY-MM-DD (İstanbul günü) → okunur tarih. */
export function fmtDay(day: string, l: CampaignLocale, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short' }): string {
  const [y, m, d] = day.split('-').map(Number);
  return new Intl.DateTimeFormat(localeTag(l), { timeZone: 'UTC', ...opts }).format(new Date(Date.UTC(y, m - 1, d)));
}

