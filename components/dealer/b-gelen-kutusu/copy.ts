const COPY: Record<InboxLocale, Copy> = { tr, en };

export function useInboxLocale(): InboxLocale {
  return useDsLocale() === 'en' ? 'en' : 'tr';
}

export function useInboxCopy(): Copy {
  return COPY[useInboxLocale()];
}

export type InboxCopy = Copy;
