/** Göreli gün metni (yalnız istemcide, hidrasyon sonrası). */
export function relativeDaysText(copy: SettingsCopy, iso: string | null | undefined, now: number): string | null {
  if (!iso) return null;
  const t = new Date(iso).getTime();
  if (Number.isNaN(t)) return null;
  const days = Math.floor((now - t) / 86_400_000);
  if (days <= 0) return copy.relative.today;
  if (days === 1) return copy.relative.yesterday;
  if (days < 30) return copy.relative.days(days);
  const months = Math.floor(days / 30);
  if (months < 12) return copy.relative.months(months);
  return copy.relative.years(Math.floor(months / 12));
}
