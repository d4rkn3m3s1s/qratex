const COPY: Record<DsLocale, Copy> = { tr: TR, en: EN };

export type InsightsCopy = Copy;

export function useInsightsCopy(): { copy: InsightsCopy; locale: DsLocale; tag: string } {
  const locale = useDsLocale();
  return { copy: COPY[locale], locale, tag: COPY[locale].tag };
}

export function getInsightsCopy(locale: DsLocale = 'tr'): InsightsCopy {
  return COPY[locale];
}

/** Yüzde biçimi: TR "%57", EN "57%". `value` yüzde cinsinden. */
export function formatPercent(value: number, tag: string, digits = 0): string {
  const v = value.toLocaleString(tag, { maximumFractionDigits: digits });
  return tag.startsWith('tr') ? `%${v}` : `${v}%`;
}

/** Göreli zaman ("3 dk önce"), İstanbul saatine bağlı değil (fark). */
export function relativeTime(iso: string, tag: string, now: number = Date.now()): string {
  const diffSec = Math.round((new Date(iso).getTime() - now) / 1000);
  const rtf = new Intl.RelativeTimeFormat(tag, { numeric: 'auto' });
  const abs = Math.abs(diffSec);
  if (abs < 45) return rtf.format(0, 'second');
  if (abs < 3600) return rtf.format(Math.round(diffSec / 60), 'minute');
  if (abs < 86_400) return rtf.format(Math.round(diffSec / 3600), 'hour');
  return rtf.format(Math.round(diffSec / 86_400), 'day');
}

export function formatDay(day: string, tag: string): string {
  const [y, m, d] = day.split('-').map(Number);
  return new Intl.DateTimeFormat(tag, { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' }).format(
    new Date(Date.UTC(y, (m ?? 1) - 1, d ?? 1))
  );
}

export function formatDateTime(iso: string, tag: string): string {
  return new Intl.DateTimeFormat(tag, {
    day: 'numeric',
    month: 'short',
    hour: '2-digit',
    minute: '2-digit',
    timeZone: 'Europe/Istanbul',
  }).format(new Date(iso));
}
